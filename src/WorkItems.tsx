import { useState } from 'react';
import { ChevronDown, Plus, Sparkles } from 'lucide-react';
import type { Issue, WorkItem } from './data';
import { ExpandRegion, StatusBadge } from './IssueHierarchy';
import { uid } from './issueModel';
function makeWork(parentId: string, title: string): WorkItem {
  const now = new Date().toISOString();
  return {
    id: uid(),
    parentWorkItemId: parentId,
    title,
    description: '',
    status: 'To Do',
    origin: 'Existing Work',
    assignee: '',
    createdAt: now,
    updatedAt: now,
    subtasks: [],
  };
}
function WorkRow({
  work,
  onChange,
  locked,
}: {
  work: WorkItem;
  onChange: (next: WorkItem) => void;
  locked: boolean;
}) {
  const [open, setOpen] = useState(false);
  const [subtask, setSubtask] = useState('');
  const [editing, setEditing] = useState(false);
  const [draftTitle, setDraftTitle] = useState(work.title);
  const [draftDescription, setDraftDescription] = useState(work.description);
  const patch = (changes: Partial<WorkItem>) =>
    onChange({ ...work, ...changes, updatedAt: new Date().toISOString() });
  return (
    <article className="cc-work-row">
      <div className="cc-work-title">
        <button aria-expanded={open} onClick={() => setOpen(!open)}>
          <ChevronDown size={14} className={open ? '' : 'closed'} />
          <strong>{work.title}</strong>
        </button>
        <StatusBadge issue={work} />
        {work.origin === 'Generated by Aria' && (
          <span className="cc-generated" title="Generated by Aria">
            <Sparkles size={12} />
          </span>
        )}
        <small>{work.subtasks.length} subtasks</small>
      </div>
      <ExpandRegion open={open}>
        <div className="cc-work-body">
          {editing ? (
            <>
              <label>
                Task title
                <input
                  aria-label="Task title"
                  value={draftTitle}
                  onChange={(e) => setDraftTitle(e.target.value)}
                />
              </label>
              <label>
                Description
                <textarea
                  value={draftDescription}
                  onChange={(e) => setDraftDescription(e.target.value)}
                />
              </label>
              <button
                className="text-button"
                disabled={!draftTitle.trim()}
                onClick={() => {
                  patch({ title: draftTitle.trim(), description: draftDescription });
                  setEditing(false);
                }}
              >
                Done editing
              </button>
            </>
          ) : (
            <>
              <p>{work.description || 'Add details to clarify the expected outcome.'}</p>
              <button
                className="text-button"
                disabled={locked}
                onClick={() => {
                  setDraftTitle(work.title);
                  setDraftDescription(work.description);
                  setEditing(true);
                }}
              >
                Edit task
              </button>
            </>
          )}
          <div className="cc-work-properties">
            <span>{work.origin}</span>
            <label title="Only mark complete after verifying the work">
              <input
                type="checkbox"
                checked={work.status === 'Completed'}
                disabled={locked}
                onChange={(e) => patch({ status: e.target.checked ? 'Completed' : 'To Do' })}
              />
              Verified complete
            </label>
          </div>
          {work.subtasks.map((sub) => (
            <div key={sub.id} className="cc-subtask">
              <label>
                <input
                  type="checkbox"
                  checked={sub.status === 'Completed'}
                  disabled={locked}
                  onChange={(e) =>
                    patch({
                      subtasks: work.subtasks.map((s) =>
                        s.id === sub.id
                          ? {
                              ...s,
                              status: e.target.checked ? 'Completed' : 'To Do',
                              updatedAt: new Date().toISOString(),
                            }
                          : s,
                      ),
                    })
                  }
                />
                {sub.title}
                {sub.origin === 'Generated by Aria' && (
                  <Sparkles size={12} aria-label="Generated by Aria" />
                )}
              </label>
              <StatusBadge issue={sub} />
            </div>
          ))}
          <form
            className="cc-add-work"
            onSubmit={(e) => {
              e.preventDefault();
              if (!subtask.trim()) return;
              patch({ subtasks: [...work.subtasks, makeWork(work.id, subtask.trim())] });
              setSubtask('');
            }}
          >
            <input
              aria-label={`New subtask for ${work.title}`}
              placeholder="Add a subtask…"
              value={subtask}
              disabled={locked}
              onChange={(e) => setSubtask(e.target.value)}
            />
            <button className="text-button" disabled={locked || !subtask.trim()}>
              <Plus size={13} />
              Add
            </button>
          </form>
        </div>
      </ExpandRegion>
    </article>
  );
}
export function WorkItems({
  issue,
  onChange,
}: {
  issue: Issue;
  onChange: (changes: Partial<Issue>) => void;
}) {
  const [title, setTitle] = useState('');
  const items = issue.workItems || [];
  return (
    <div className="cc-work-items">
      <div className="cc-work-intro">
        <p>Implementation tasks stay with this issue, independently of Aria’s plans.</p>
        <small>
          {items.filter((w) => w.status === 'Completed').length}/{items.length} completed
        </small>
      </div>
      {items.map((work) => (
        <WorkRow
          key={work.id}
          work={work}
          locked={issue.run?.phase === 'executing' && work.runId === issue.run.id}
          onChange={(next) =>
            onChange({ workItems: items.map((w) => (w.id === next.id ? next : w)) })
          }
        />
      ))}
      {!items.length && (
        <p className="cc-small-empty">
          No implementation tasks yet. Add existing work below, or approve an Aria plan.
        </p>
      )}
      <form
        className="cc-add-work"
        onSubmit={(e) => {
          e.preventDefault();
          if (!title.trim()) return;
          onChange({ workItems: [...items, makeWork(`issue-${issue.id}`, title.trim())] });
          setTitle('');
        }}
      >
        <input
          aria-label="New implementation task"
          placeholder="Add an implementation task…"
          maxLength={160}
          value={title}
          onChange={(e) => setTitle(e.target.value)}
        />
        <button className="button" disabled={!title.trim()}>
          <Plus size={14} />
          Add task
        </button>
      </form>
    </div>
  );
}
