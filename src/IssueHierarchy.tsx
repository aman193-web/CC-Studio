import { useLayoutEffect, useRef, useState } from 'react';
import type { ReactNode } from 'react';
import { gsap } from 'gsap';
import { CheckCircle2, ChevronDown, Circle, GitBranch, Plus, Sparkles } from 'lucide-react';
import type { Issue, Status, WorkType } from './data';
import { workTypeOf, parentError, secondaryStatus } from './issueModel';
import { AriaAction } from './AriaAction';

export function useIssueMotion<T extends HTMLElement = HTMLDivElement>(key: unknown) {
  const ref = useRef<T>(null);
  useLayoutEffect(() => {
    const mm = gsap.matchMedia();
    mm.add('(prefers-reduced-motion: no-preference)', () => {
      if (!ref.current) return;
      const context = gsap.context(() => {
        gsap.fromTo(
          ref.current,
          { opacity: 0.5, y: 3 },
          { opacity: 1, y: 0, duration: 0.22, clearProps: 'opacity,transform' },
        );
      }, ref);
      return () => context.revert();
    });
    return () => mm.revert();
  }, [key]);
  return ref;
}
export function ExpandRegion({
  open,
  children,
  id,
}: {
  open: boolean;
  children: ReactNode;
  id?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const mm = gsap.matchMedia();
    mm.add('(prefers-reduced-motion: no-preference)', () => {
      el.hidden = false;
      const tween = gsap.fromTo(
        el,
        { height: open ? 0 : el.scrollHeight, opacity: open ? 0 : 1 },
        {
          height: open ? el.scrollHeight : 0,
          opacity: open ? 1 : 0,
          duration: 0.22,
          ease: 'power2.out',
          onComplete: () => {
            el.hidden = !open;
            el.style.height = open ? 'auto' : '0px';
          },
        },
      );
      return () => tween.kill();
    });
    mm.add('(prefers-reduced-motion: reduce)', () => {
      el.hidden = !open;
      el.style.height = open ? 'auto' : '0px';
    });
    return () => mm.revert();
  }, [open]);
  return (
    <div ref={ref} id={id} className="cc-expand-region" inert={!open} aria-hidden={!open}>
      {children}
    </div>
  );
}
export function IssueLabels({ issue }: { issue: Issue }) {
  const labels = [workTypeOf(issue)];
  const ref = useIssueMotion(labels.join(','));
  return (
    <div ref={ref} className="cc-labels">
      {(labels.length ? labels : ['Issue']).map((label) => (
        <span key={label} className={`cc-type ${label.toLowerCase()}`}>
          {label}
        </span>
      ))}
      {issue.origin === 'Generated by Aria' && (
        <span className="cc-generated" title="Generated by Aria">
          <Sparkles size={12} />
          Aria
        </span>
      )}
    </div>
  );
}
export function WorkTypePicker({
  value,
  onChange,
}: {
  value: WorkType;
  onChange: (value: WorkType) => void;
}) {
  return (
    <fieldset className="cc-work-type-picker">
      <legend>Work type</legend>
      <div>
        {(['Issue', 'Story', 'Epic'] as const).map((type) => (
          <label key={type} className={value === type ? 'selected' : ''}>
            <input
              type="radio"
              name="work-type"
              value={type}
              checked={value === type}
              onChange={() => onChange(type)}
            />
            {type}
          </label>
        ))}
      </div>
      <p>Helps Aria understand the scope of your plan.</p>
    </fieldset>
  );
}
export function StatusBadge({ issue }: { issue: Pick<Issue, 'status' | 'run' | 'legacyStatus'> }) {
  const ref = useIssueMotion<HTMLSpanElement>(issue.status);
  return (
    <span
      ref={ref}
      className={`cc-status ${issue.status.toLowerCase().replaceAll(' ', '-')}`}
      title={issue.status === 'AI Working' ? 'Aria is executing approved work' : undefined}
    >
      {issue.status === 'Completed' ? (
        <CheckCircle2 size={14} />
      ) : issue.status === 'AI Working' ? (
        <span className="cc-progress-dot" />
      ) : (
        <Circle size={14} />
      )}
      {issue.status}
    </span>
  );
}
export function SecondaryBadge({ issue }: { issue: Issue }) {
  const text = secondaryStatus(issue);
  return text ? (
    <span
      className={`cc-secondary-state ${issue.run?.phase === 'clarification' ? 'needs-input' : ''}`}
    >
      {text}
    </span>
  ) : null;
}
export function ChildIssues({
  issue,
  issues,
  onOpen,
  onFix,
  onCreate,
  onAssociate,
}: {
  issue: Issue;
  issues: Issue[];
  onOpen: (id: number) => void;
  onFix: (id: number) => void;
  onCreate: (parent: number) => void;
  onAssociate: (id: number, parentId: number | null) => void;
}) {
  const [open, setOpen] = useState(true);
  const [link, setLink] = useState(false);
  const children = issues.filter((i) => i.parentIssueId === issue.id);
  const done = children.filter((i) => i.status === 'Completed').length;
  const candidates = issues.filter(
    (i) => i.parentIssueId !== issue.id && !parentError(i, issue.id, issues),
  );
  return (
    <section className="cc-child-issues">
      <div className="cc-section-heading">
        <button className="cc-child-heading" aria-expanded={open} onClick={() => setOpen(!open)}>
          <ChevronDown size={15} className={open ? '' : 'closed'} />
          <h2>Child issues</h2>
          <span>
            {done}/{children.length} completed
          </span>
        </button>
        <div className="cc-inline-actions">
          <button className="text-button" onClick={() => setLink(!link)}>
            Link existing
          </button>
          <button className="text-button" onClick={() => onCreate(issue.id)}>
            <Plus size={14} />
            New child
          </button>
        </div>
      </div>
      {link && (
        <label className="cc-associate-picker">
          Choose an issue
          <select
            aria-label="Link existing child issue"
            defaultValue=""
            onChange={(e) => {
              if (e.target.value) {
                onAssociate(Number(e.target.value), issue.id);
                setLink(false);
                setOpen(true);
              }
            }}
          >
            <option value="">Select an issue…</option>
            {candidates.map((i) => (
              <option key={i.id} value={i.id}>
                #{i.id} · {i.title}
                {i.parentIssueId ? ' (reassign)' : ''}
              </option>
            ))}
          </select>
          {!candidates.length && <small>No compatible issues available.</small>}
        </label>
      )}
      <ExpandRegion open={open}>
        <div className="cc-child-list">
          {children.map((child) => (
            <div key={child.id} className="cc-child-row">
              <GitBranch size={14} />
              <div className="cc-child-title">
                <button onClick={() => onOpen(child.id)}>
                  <small>#{child.id}</small> {child.title}
                </button>
                <IssueLabels issue={child} />
              </div>
              <span className="cc-child-priority">{child.priority}</span>
              <StatusBadge issue={child} />
              <AriaAction issue={child} onClick={() => onFix(child.id)} />
              <button
                className="text-button"
                aria-label={`Unlink issue #${child.id}`}
                onClick={() => onAssociate(child.id, null)}
              >
                Unlink
              </button>
            </div>
          ))}
          {!children.length && (
            <p className="cc-small-empty">
              No child issues. Add one when this work needs a separate outcome.
            </p>
          )}
        </div>
      </ExpandRegion>
    </section>
  );
}
export const statusClass = (status: Status) => status.toLowerCase().replaceAll(' ', '-');
