import type { Issue, Run, Status, WorkItem } from './data';
export const PROJECT_ID = 'realtime';
export const labelsOf = (issue: Pick<Issue, 'label' | 'labels'>) => [
  ...new Set(issue.labels ?? (issue.label ? [issue.label] : [])),
];
export const hasLabel = (issue: Pick<Issue, 'label' | 'labels'>, label: string) =>
  labelsOf(issue).includes(label);
export const hierarchyKind = (issue: Pick<Issue, 'label' | 'labels'>) =>
  hasLabel(issue, 'Epic') ? 'Epic' : hasLabel(issue, 'Story') ? 'Story' : 'Regular';
export const uid = () => crypto.randomUUID();
export function ancestors(issue: Issue, issues: Issue[]): Issue[] {
  const result: Issue[] = [],
    seen = new Set([issue.id]);
  let parent = issues.find((i) => i.id === issue.parentIssueId);
  while (parent && !seen.has(parent.id)) {
    seen.add(parent.id);
    result.unshift(parent);
    parent = issues.find((i) => i.id === parent!.parentIssueId);
  }
  return result;
}
export function association(issue: Issue, issues: Issue[], label: string) {
  return [...ancestors(issue, issues), issue].find((i) => hasLabel(i, label));
}
export function parentError(
  issue: Issue,
  parentId: number | null | undefined,
  issues: Issue[],
): string | null {
  if (parentId == null) return null;
  const parent = issues.find((i) => i.id === parentId);
  if (!parent) return 'The selected parent no longer exists.';
  if (parent.id === issue.id) return 'An issue cannot be its own parent.';
  if ((parent.projectId || PROJECT_ID) !== (issue.projectId || PROJECT_ID))
    return 'Choose a parent from the same project.';
  if (ancestors(parent, issues).some((i) => i.id === issue.id))
    return 'This relationship would create a cycle.';
  const kind = hierarchyKind(issue),
    parentKind = hierarchyKind(parent);
  if (kind === 'Epic') return 'An Epic must be a top-level issue.';
  if (kind === 'Story' && parentKind !== 'Epic')
    return 'A Story can belong to an Epic or stand alone.';
  return null;
}
export function validateIssue(issue: Issue, issues: Issue[]): string | null {
  if (hasLabel(issue, 'Epic') && hasLabel(issue, 'Story'))
    return 'Choose either Epic or Story, not both.';
  const error = parentError(issue, issue.parentIssueId, issues);
  if (error) return error;
  const next = issues.map((i) => (i.id === issue.id ? issue : i));
  for (const child of next.filter((i) => i.parentIssueId === issue.id)) {
    const childError = parentError(child, issue.id, next);
    if (childError) return 'Reassign the child Stories before changing this Epic label.';
  }
  return null;
}
export function searchIssue(issue: Issue, issues: Issue[], query: string) {
  return [
    issue.title,
    issue.description,
    `#${issue.id}`,
    `CC-${issue.id}`,
    ...labelsOf(issue),
    ...ancestors(issue, issues).map((i) => i.title),
  ]
    .join(' ')
    .toLowerCase()
    .includes(query.toLowerCase().trim());
}
export function secondaryStatus(issue: Issue) {
  if (issue.status === 'Completed') return '';
  if (issue.run?.phase === 'clarification') return 'Needs input';
  if (issue.run?.phase === 'plan') return 'Awaiting approval';
  if (issue.run?.phase === 'analyzing') return 'Planning';
  if (issue.run?.phase === 'completed' && !issue.run.verified) return 'Awaiting verification';
  if (issue.legacyStatus === 'In review') return 'Awaiting verification';
  if (issue.legacyStatus === 'In progress') return 'Ready to resume';
  return '';
}
export function workFromPlan(issue: Issue, run: Run): WorkItem[] {
  const now = issue.updatedAt || issue.createdAt || '2026-11-27T00:00:00Z';
  return run.tasks
    .filter((t) => t.enabled)
    .map((task, index) => {
      const id = task.workItemId || `issue-${issue.id}-${run.planId || 'legacy'}-task-${task.id}`;
      const status: Status = index < run.step ? 'Completed' : 'To Do';
      return {
        id,
        parentWorkItemId: `issue-${issue.id}`,
        title: task.title,
        description: task.detail,
        status,
        origin: 'Generated by Aria',
        assignee: task.agent === 'Auto-select' ? 'Aria' : task.agent,
        createdAt: now,
        updatedAt: now,
        planId: run.planId,
        runId: run.id,
        subtasks: (task.subtasks || []).map((title, n) => ({
          id: `${id}-sub-${n}`,
          parentWorkItemId: id,
          title,
          description: '',
          status,
          origin: 'Generated by Aria',
          assignee: task.agent === 'Auto-select' ? 'Aria' : task.agent,
          createdAt: now,
          updatedAt: now,
          planId: run.planId,
          runId: run.id,
          subtasks: [],
        })),
      };
    });
}
export function reconcileApprovedWork(issue: Issue, run: Run) {
  const existing = issue.workItems || [];
  const generated = workFromPlan(issue, run);
  return [...existing, ...generated.filter((w) => !existing.some((e) => e.id === w.id))];
}
export function migrationStatus(rawStatus: string, run?: Run): Status {
  if (rawStatus === 'Done' || rawStatus === 'Completed') return 'Completed';
  if (run?.phase === 'completed' && run.verified) return 'Completed';
  if (run?.phase === 'executing' && run.approvedAt && run.startedAt) return 'AI Working';
  return 'To Do';
}
export function migrateIssues(raw: Issue[]): Issue[] {
  const seen = new Set<number>();
  const result = raw
    .filter((i) => !seen.has(i.id) && !!seen.add(i.id))
    .map((i) => {
      const labels = labelsOf(i).filter((l) => !(l === 'Story' && hasLabel(i, 'Epic')));
      const legacy = String(i.status);
      const run = i.run
        ? {
            ...i.run,
            id: i.run.id || `legacy-run-${i.id}`,
            planId: i.run.planId || `legacy-plan-${i.id}`,
            mode: i.run.mode || ('preview' as const),
          }
        : undefined;
      if (run?.phase === 'executing' && !run.approvedAt)
        run.approvedAt = i.updatedAt || '2026-11-27T00:00:00Z';
      const issue: Issue = {
        ...i,
        projectId: i.projectId || PROJECT_ID,
        labels,
        label: labels[0] || '',
        status: migrationStatus(legacy, run),
        legacyStatus:
          i.legacyStatus || (['In progress', 'In review'].includes(legacy) ? legacy : undefined),
        parentIssueId: i.parentIssueId ?? null,
        origin: i.origin || 'Existing Work',
        run,
        runHistory: i.runHistory || [],
        workItems: i.workItems || [],
      };
      // Only approved/previously executed work becomes permanent. Draft plans stay drafts.
      if (run && ['executing', 'completed'].includes(run.phase))
        issue.workItems = reconcileApprovedWork(issue, run);
      if (run)
        run.tasks = run.tasks.map((t) => ({
          ...t,
          workItemId:
            t.workItemId || issue.workItems?.find((w) => w.id.endsWith(`-task-${t.id}`))?.id,
        }));
      return issue;
    });
  // Repair invalid imported relationships without dropping issues or their content.
  for (const issue of result)
    if (parentError(issue, issue.parentIssueId, result)) issue.parentIssueId = null;
  return result;
}
export function newIssueData(id: number, title: string, labels: string[] = ['Task']): Issue {
  const now = new Date().toISOString();
  return {
    id,
    title,
    description: '',
    labels,
    label: labels[0] || '',
    projectId: PROJECT_ID,
    parentIssueId: null,
    status: 'To Do',
    priority: 'Medium',
    assignee: '',
    source: 'Studio',
    comments: 0,
    date: 'Just now',
    origin: 'Existing Work',
    createdAt: now,
    updatedAt: now,
    workItems: [],
    runHistory: [],
  };
}
